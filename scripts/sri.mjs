#!/usr/bin/env node
// Subresource Integrity for a browser page (web/verifier/, and the signing page).
// Run by scripts/build-verifier.sh, and by the signing page's build, after the module is built:
//
//   node scripts/sri.mjs web/verifier
//
// 1. Hashes (sha384) every .wasm and .js file of the page directory, and every script and
//    stylesheet the page's template references, and prints the hashes.
// 2. Writes <dir>/integrity.json: {"file": "sha384-..."}, the list a host deploying these files
//    (the hosted signer page) needs.
// 3. Writes <dir>/index.html from <dir>/index.template.html with:
//    - an `integrity` attribute on every <script src> and <link rel="stylesheet">;
//    - an import map whose `integrity` section lists every .js and .wasm file, so the browser
//      checks the modules a script imports, and the page's own code can fetch the WebAssembly
//      module and the worker script with the right hash (signer-client.js, verifier.js);
//    - the import map's own hash added to the CSP's script-src (it is an inline script).
//
// index.html and integrity.json are build outputs (git-ignored): a page whose files changed
// since the last build refuses to load until it is built again. The hashes are of the bytes on
// disk, so a checkout with CRLF line endings gets its own (consistent) hashes.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const dir = process.argv[2];
if (!dir || !existsSync(join(dir, "index.template.html"))) {
  console.error("usage: node scripts/sri.mjs <page directory with index.template.html>");
  process.exit(2);
}

const sri = (path) => `sha384-${createHash("sha384").update(readFileSync(path)).digest("base64")}`;
const template = readFileSync(join(dir, "index.template.html"), "utf8");

// Local references of the template (relative URLs only; the pages load nothing from elsewhere).
const tag = /<(script|link)\b[^>]*>/g;
const urlOf = (t) => (t.match(/\b(?:src|href)="([^"]+)"/) || [])[1];
const isLocal = (u) => u && !/^[a-z]+:|^\/\//i.test(u);

const hashes = new Map(); // URL relative to the page -> hash
for (const name of readdirSync(dir).sort()) {
  if (/\.(js|wasm)$/.test(name)) hashes.set(`./${name}`, sri(join(dir, name)));
}
for (const [t] of template.matchAll(tag)) {
  const u = urlOf(t);
  const isAsset = t.startsWith("<script") || /\brel="stylesheet"/.test(t);
  if (isAsset && isLocal(u)) {
    const key = u.startsWith(".") ? u : `./${u}`;
    if (!hashes.has(key)) hashes.set(key, sri(resolve(dir, u)));
  }
}

const importMap = JSON.stringify({
  integrity: Object.fromEntries([...hashes].filter(([u]) => /\.(js|wasm)$/.test(u))),
});
const mapHash = `'sha256-${createHash("sha256").update(importMap).digest("base64")}'`;

let html = template.replace(tag, (t) => {
  const u = urlOf(t);
  const key = u && (u.startsWith(".") ? u : `./${u}`);
  if (!key || !hashes.has(key) || /\bintegrity=/.test(t)) return t;
  return t.replace(/\s*\/?>$/, (end) => ` integrity="${hashes.get(key)}"${end}`);
});
if (!/script-src [^;"]*/.test(html)) throw new Error("the template's CSP has no script-src");
html = html.replace(/script-src ([^;"]*)/, (m) => `${m} ${mapHash}`);
html = html.replace(/(\s*)<script\b/, (m, space) => `${space}<script type="importmap">${importMap}</script>${m}`);
html = html.replace(
  /<!-- Template:[\s\S]*?-->/,
  "<!-- Generated by scripts/sri.mjs from index.template.html: edit the template, then rebuild. -->",
);
writeFileSync(join(dir, "index.html"), html);

const list = Object.fromEntries([...hashes].map(([u, h]) => [u.replace(/^\.\//, ""), h]));
writeFileSync(join(dir, "integrity.json"), `${JSON.stringify(list, null, 2)}\n`);

const shown = relative(process.cwd(), dir) || dir;
for (const [u, h] of Object.entries(list)) console.log(`${h}  ${join(shown, u)}`);
console.log(`Wrote ${join(shown, "index.html")} and ${join(shown, "integrity.json")}`);
