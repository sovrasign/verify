  /** The page's language: a saved choice if it is one of ours, else the browser's first match. */
  function pickLanguage(saved, preferred) {
    if (saved && STRINGS[saved]) return saved;
    for (const tag of preferred || []) {
      const base = String(tag).toLowerCase().split("-")[0];
      if (STRINGS[base]) return base;
    }
    return "en";
  }

  /** A string in `lang` with its {placeholders} filled; English when a key is missing. */
  function t(lang, key, params) {
    const table = STRINGS[lang] || STRINGS.en;
    let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : STRINGS.en[key];
    if (s === undefined) return key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, (m, name) =>
        Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m);
    }
    return s;
  }

  /**
   * The provider's display name: the trust list's name for the issuer, else its address. Names
   * of providers (Google, Microsoft...) are never translated.
   */
  function providerName(issuer, trust) {
    const entry = ((trust && trust.issuers) || []).find((i) => i.issuer === issuer);
    return (entry && entry.name) || issuer || "?";
  }

  /**
   * One piece of identity evidence in words: the method and who vouched for it. Where trust rests
   * on the provider that ran the check for the signer (a one-time email code, a phone code, an
   * identity document check) the line says "via <that provider>", as the hosted service's
   * certificate and apps do ("via SignPDF").
   */
  function basisText(lang, b, trust) {
    const provider = providerName(b.issuer, trust);
    const via = t(lang, "via", { service: provider });
    switch (b.method) {
      case "email-code":
        return t(lang, "basis_email_code", { via });
      case "account":
        return t(lang, "basis_account", { provider });
      case "organization":
        return b.organization
          ? t(lang, "basis_organization", { org: b.organization, provider })
          : t(lang, "basis_organization_plain", { provider });
      case "phone":
        return t(lang, "basis_phone", { via });
      case "id-document":
        return t(lang, "basis_id_document", { via });
      case "qualified":
        return t(lang, "basis_qualified", { provider });
      default:
        return t(lang, "basis_other", { method: b.method, provider });
    }
  }

  /** The level badge ("L2 Account") and its long form ("Assurance level 2 of 5"). */
  function levelText(lang, level) {
    const name = t(lang, `level_${level}`);
    const n = String(level).replace(/^L/, "");
    return {
      badge: name === `level_${level}` ? String(level) : `${level} ${name}`,
      long: t(lang, "level_of", { n }),
    };
  }

  globalThis.SignpdfI18n = { LANGUAGES, REVIEWED, STRINGS, pickLanguage, t, providerName, basisText, levelText };
